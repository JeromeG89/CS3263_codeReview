#!/usr/bin/env python
"""Assemble report/report.md from report/sections/*.md.

Figure placeholders `[FIG: ... — figN_name.png]` become Markdown images, and table
placeholders are filled from results/analysis/tables.md (generated by analyze.py).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ROOT / "report" / "sections"
TABLES = ROOT / "results" / "analysis" / "tables.md"

HEADER = """\
# AI Assistant for Software Engineering: Direct LLM Review vs. LLM-to-Z3 Translation for Verifying C Safety Invariants

**CS3263 Project Report** — Jerome Goh (A0307923A, team lead), Mothiki Eswara Anirudh (A0308802J), Goh Joon Xiang (A0307578R)

Companion documents: `report/IMPLEMENTATION.md` (full implementation write-up), `report/APPENDIX_A_DATASET.md`
(every instance, precondition and reference Z3 encoding), `report/APPENDIX_B_PROMPTS.md` (every prompt, verbatim).

---
"""

TABLE_SECTIONS = {
    "McNemar": "McNemar exact tests (paired by instance, Holm-corrected)",
    "code features": "Static features of the generated Z3 code (final attempt)",
}


def table_block(title: str) -> str:
    if not TABLES.exists():
        return f"_(table '{title}' not generated yet; run scripts/analyze.py)_"
    text = TABLES.read_text()
    m = re.search(rf"^## {re.escape(title)}\n\n(.*?)(?=^## |\Z)", text, flags=re.M | re.S)
    return m.group(1).strip() if m else f"_(table '{title}' not found)_"


def fill(md: str, with_figures: bool) -> str:
    def fig(m):
        if not with_figures:
            return " (Section 6)"
        inner = m.group(1)
        f = re.search(r"(fig\d+_[\w]+\.png)", inner)
        if not f:
            return ""
        cap = inner.split("—")[0].split(",")[0].strip().rstrip(":")
        return f"\n\n![{cap}](figures/{f.group(1)})\n\n"

    md = re.sub(r"\[FIG: ([^\]]+)\]", fig, md)

    def tab(m):
        inner = m.group(1)
        for key, title in TABLE_SECTIONS.items():
            if key.lower() in inner.lower():
                return "\n\n" + table_block(title) + "\n\n"
        return ""

    md = re.sub(r"\[TABLE: ([^\]]+)\]", tab, md)
    md = re.sub(r"\s*\[REF: [^\]]+\]", "", md)
    md = re.sub(r"\s*\[SECTIONS: [^\]]+\]", "", md)
    md = re.sub(r"\n{3,}", "\n\n", md)
    return md


def main():
    parts = [HEADER]
    for path in sorted(SECTIONS.glob("*.md")):
        parts.append(fill(path.read_text(), with_figures=path.name.startswith("06_")).strip() + "\n")
    out = ROOT / "report" / "report.md"
    out.write_text("\n\n".join(parts))
    left = re.findall(r"\[(?:FIG|TABLE|CHECK|TODO|CONFIRM|LLAMA[^\]]*|L)\b[^\]]*\]", out.read_text())
    print(f"wrote {out} ({len(out.read_text().split())} words); unresolved placeholders: {left}")
    sys.exit(0)


if __name__ == "__main__":
    main()
